begin;

do $$
begin
  if to_regclass('public.profiles') is null then
    raise exception 'ORI-29 requires the integrated ORI-20 public.profiles schema and role protection migrations.';
  end if;
end;
$$;

create table public.condominiums (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  address text not null,
  manager_id uuid not null references public.profiles(id) on delete restrict on update restrict,
  slug text not null,
  constraint condominiums_name_not_blank check (name ~ '[^[:space:]]'),
  constraint condominiums_address_not_blank check (address ~ '[^[:space:]]'),
  constraint condominiums_slug_format check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*-[0-9a-f]{32}$'),
  constraint condominiums_slug_key unique (slug)
);

create index condominiums_manager_id_idx on public.condominiums (manager_id);

create function public.set_condominium_slug()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  initial_name text;
begin
  if TG_OP = 'INSERT' then
    if NEW.slug is not null then
      raise exception using errcode = '23514', message = 'Condominium slug must be generated by the database.';
    end if;

    initial_name := trim(both '-' from regexp_replace(
      translate(lower(NEW.name), 'áàâãäéèêëíìîïóòôõöúùûüçñ', 'aaaaaeeeeiiiiooooouuuucn'),
      '[^a-z0-9]+', '-', 'g'
    ));
    NEW.slug := coalesce(nullif(initial_name, ''), 'condominium') || '-' || replace(gen_random_uuid()::text, '-', '');
  else
    if NEW.slug is distinct from OLD.slug then
      raise exception using errcode = '23514', message = 'Condominium slug is immutable.';
    end if;
    if NEW.manager_id is distinct from OLD.manager_id then
      raise exception using errcode = '23514', message = 'Condominium manager is immutable.';
    end if;
  end if;

  return NEW;
end;
$$;

revoke all on function public.set_condominium_slug() from public, anon, authenticated, service_role;

create trigger condominiums_slug
before insert or update on public.condominiums
for each row execute function public.set_condominium_slug();

alter table public.condominiums enable row level security;
alter table public.condominiums force row level security;

revoke all on table public.condominiums from public, anon, authenticated, service_role;

grant select on public.condominiums to authenticated;
grant insert (name, address, manager_id) on public.condominiums to authenticated;
grant update (name, address) on public.condominiums to authenticated;

create policy condominiums_select_own on public.condominiums
for select to authenticated
using (
  manager_id = (select auth.uid())
  and exists (
    select 1 from public.profiles as profile
    where profile.id = (select auth.uid()) and profile.is_sindico = true
  )
);

create policy condominiums_insert_own on public.condominiums
for insert to authenticated
with check (
  manager_id = (select auth.uid())
  and exists (
    select 1 from public.profiles as profile
    where profile.id = (select auth.uid()) and profile.is_sindico = true
  )
);

create policy condominiums_update_own on public.condominiums
for update to authenticated
using (
  manager_id = (select auth.uid())
  and exists (
    select 1 from public.profiles as profile
    where profile.id = (select auth.uid()) and profile.is_sindico = true
  )
)
with check (
  manager_id = (select auth.uid())
  and exists (
    select 1 from public.profiles as profile
    where profile.id = (select auth.uid()) and profile.is_sindico = true
  )
);

commit;
