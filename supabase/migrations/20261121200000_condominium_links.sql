begin;

alter table public.condominiums drop constraint condominiums_slug_format;
alter table public.condominiums add constraint condominiums_slug_format check (
  slug ~ '^[a-z0-9]+(-[a-z0-9]+)*-([0-9a-f]{32}|[a-z0-9]{4})$'
);

create or replace function public.set_condominium_slug()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare
  stem text;
  suffix text := '';
  sample integer;
begin
  if TG_OP = 'INSERT' then
    if NEW.slug is not null then
      raise exception using errcode = '23514', message = 'Condominium slug must be generated by the database.';
    end if;
    stem := trim(both '-' from regexp_replace(
      translate(lower(NEW.name), 'áàâãäéèêëíìîïóòôõöúùûüçñ', 'aaaaaeeeeiiiiooooouuuucn'),
      '[^a-z0-9]+', '-', 'g'
    ));
    stem := regexp_replace(stem, '^((residencial|edificio|condominio)-)+|^(residencial|edificio|condominio)$', '');
    stem := coalesce(nullif(rtrim(left(stem, 40), '-'), ''), 'condominio');
    while length(suffix) < 4 loop
      sample := get_byte(extensions.gen_random_bytes(1), 0);
      if sample < 252 then
        suffix := suffix || substr('abcdefghijklmnopqrstuvwxyz0123456789', sample % 36 + 1, 1);
      end if;
    end loop;
    NEW.slug := stem || '-' || suffix;
  else
    if NEW.slug is distinct from OLD.slug or NEW.manager_id is distinct from OLD.manager_id then
      raise exception using errcode = '23514', message = 'Condominium identity is immutable.';
    end if;
  end if;
  return NEW;
end;
$$;

create function public.create_condominium(p_name text, p_address text)
returns setof public.condominiums language plpgsql security invoker set search_path = '' as $$
declare
  attempt integer;
begin
  for attempt in 1..8 loop
    begin
      return query insert into public.condominiums (name, address, manager_id)
        values (p_name, p_address, auth.uid()) returning *;
      return;
    exception when unique_violation then
      if attempt = 8 then raise; end if;
    end;
  end loop;
end;
$$;
revoke all on function public.create_condominium(text, text) from public, anon;
grant execute on function public.create_condominium(text, text) to authenticated;

create function public.resolve_condominium_link(p_slug text)
returns table (name text, address text)
language sql stable security definer set search_path = '' as $$
  select c.name, c.address from public.condominiums c where c.slug = p_slug limit 1;
$$;
revoke all on function public.resolve_condominium_link(text) from public;
grant execute on function public.resolve_condominium_link(text) to anon, authenticated;

commit;
